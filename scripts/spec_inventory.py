#!/usr/bin/env python3
"""Requirement inventory for spec Parts VIII and IX (STRATA-SYS-*, STRATA-ARCH-*).

The spec's work breakdowns (VIII.30, IX.43) list every requirement once, with
phase, area, level and goal. This script joins them with the hand-maintained
status file docs/project/perf-status.toml and writes
docs/project/PERF_INVENTORY.md. Requirements without an entry are MISSING:
nothing is marked implemented because the spec describes it (Part VI).

    scripts/spec_inventory.py          # regenerate the inventory
    scripts/spec_inventory.py --check  # fail if it is stale or the status
                                       # file names unknown IDs / statuses
"""

import re
import sys
import tomllib
from collections import Counter, OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "docs/spec/StrataDB_Master_Engineering_Specification.md"
STATUS = ROOT / "docs/project/perf-status.toml"
OUT = ROOT / "docs/project/PERF_INVENTORY.md"

STATUSES = ["IMPLEMENTED", "PARTIAL", "MISSING", "BLOCKED", "DEFERRED"]
TICKET = re.compile(
    r"^### (?:SYS|ARCH)-T\d+ — (?:implement )?`(STRATA-(?:SYS|ARCH)-\d+-\d+)` \(([^,]+), (MUST|SHOULD|MAY)\)"
)
PHASE = re.compile(r"^## (?:VIII\.30\.\d+ Phase (P\d)|IX\.43\.(A\d) Phase)")
GOAL = re.compile(r"^-\s+\*\*Goal:\*\*\s*(.*)")


def parse_spec():
    reqs = OrderedDict()
    phase = None
    current = None
    for line in SPEC.read_text(encoding="utf-8").splitlines():
        m = PHASE.match(line)
        if m:
            phase = m.group(1) or m.group(2)
            continue
        if line.startswith("# ") and not line.startswith("# VIII.30") and not line.startswith("# IX.43"):
            phase = None  # left a work-breakdown chapter
        m = TICKET.match(line)
        if m and phase:
            rid, area, level = m.groups()
            if rid in reqs:
                raise SystemExit(f"duplicate ticket for {rid}")
            current = rid
            reqs[rid] = {"phase": phase, "area": area.strip(), "level": level, "goal": ""}
            continue
        m = GOAL.match(line)
        if m and current and not reqs[current]["goal"]:
            reqs[current]["goal"] = m.group(1).strip()
    return reqs


def load_status(reqs):
    data = tomllib.loads(STATUS.read_text(encoding="utf-8"))
    errors = []
    out = {}
    for rid, entry in data.get("req", {}).items():
        if rid not in reqs:
            errors.append(f"{STATUS.name}: unknown requirement {rid}")
            continue
        st = entry.get("status")
        if st not in STATUSES:
            errors.append(f"{STATUS.name}: {rid} has invalid status {st!r}")
            continue
        if st in ("IMPLEMENTED", "PARTIAL") and not entry.get("evidence"):
            errors.append(f"{STATUS.name}: {rid} is {st} but names no evidence")
        if st in ("BLOCKED", "DEFERRED", "PARTIAL") and not entry.get("note"):
            errors.append(f"{STATUS.name}: {rid} is {st} but gives no reason (note)")
        out[rid] = entry
    return out, errors


def cell(s):
    return s.replace("|", "\\|").replace("\n", " ")


def render(reqs, status):
    phases = OrderedDict()
    for rid, r in reqs.items():
        phases.setdefault(r["phase"], []).append(rid)
    total = Counter(status.get(r, {}).get("status", "MISSING") for r in reqs)
    must = Counter(
        status.get(r, {}).get("status", "MISSING") for r, v in reqs.items() if v["level"] == "MUST"
    )
    lines = [
        "# Performance and architecture requirement inventory (spec Parts VIII–IX)",
        "",
        "<!-- Generated by scripts/spec_inventory.py from the spec work breakdowns",
        "     (VIII.30, IX.43) and docs/project/perf-status.toml. Do not edit by hand. -->",
        "",
        "Status vocabulary (Part VI): `IMPLEMENTED` (code + tests exist; *not* the same",
        "as performance-accepted — no requirement here is PERF-ACCEPTED, because no",
        "HW-REF-1 runner exists), `PARTIAL`, `MISSING`, `BLOCKED` (cannot be done or",
        "verified in this environment), `DEFERRED` (later phase by decision, ADR-0026).",
        "Requirements without a status entry are `MISSING`.",
        "",
        f"**{len(reqs)} requirements** — "
        + ", ".join(f"{s} {total.get(s, 0)}" for s in STATUSES)
        + f". MUST only: "
        + ", ".join(f"{s} {must.get(s, 0)}" for s in STATUSES)
        + ".",
        "",
        "| Phase | Requirements | " + " | ".join(STATUSES) + " |",
        "|---|---|" + "---|" * len(STATUSES),
    ]
    for ph, ids in phases.items():
        c = Counter(status.get(r, {}).get("status", "MISSING") for r in ids)
        lines.append(f"| {ph} | {len(ids)} | " + " | ".join(str(c.get(s, 0)) for s in STATUSES) + " |")
    for ph, ids in phases.items():
        lines += ["", f"## Phase {ph}", "", "| ID | Level | Area | Status | Requirement | Evidence / note |", "|---|---|---|---|---|---|"]
        for rid in ids:
            r = reqs[rid]
            e = status.get(rid, {})
            st = e.get("status", "MISSING")
            ev = "; ".join(x for x in (e.get("evidence", ""), e.get("note", "")) if x)
            goal = r["goal"] if len(r["goal"]) <= 220 else r["goal"][:217] + "…"
            lines.append(f"| {rid} | {r['level']} | {cell(r['area'])} | {st} | {cell(goal)} | {cell(ev)} |")
    return "\n".join(lines) + "\n"


def main():
    reqs = parse_spec()
    if len(reqs) == 0:
        raise SystemExit("no requirements parsed from the spec")
    status, errors = load_status(reqs)
    text = render(reqs, status)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            errors.append(f"{OUT.relative_to(ROOT)} is stale: run scripts/spec_inventory.py")
        for e in errors:
            print(e, file=sys.stderr)
        sys.exit(1 if errors else 0)
    for e in errors:
        print(e, file=sys.stderr)
    if errors:
        sys.exit(1)
    OUT.write_text(text, encoding="utf-8")
    print(f"{len(reqs)} requirements -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
